/**
 * Regenerates `tsconfig.pi-paths.json` from the vendored pi monorepo tsconfig.
 *
 * Why this exists: pi's packages are published with `exports` pointing at
 * `./dist/*`, and this project runs their TypeScript sources directly. Bare
 * imports like `@earendil-works/pi-ai` therefore fail to resolve. We solve it by
 * mirroring the vendored `tsconfig.json`'s `compilerOptions.paths` and rewriting
 * each target to point into `vendor/pi/packages/*\/src`.
 *
 * tsx honours these paths at runtime and esbuild honours them at build time, so
 * one mapping serves both.
 *
 * The mappings are derived from upstream rather than hand-written because pi
 * carries hand-tuned subpath entries (`pi-coding-agent/hooks` -> `src/core/hooks/index.ts`)
 * that a naive `<package>/*` wildcard does not reproduce.
 *
 * Run after `npm run vendor:pi`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { PI_PACKAGES } from "./pi-packages.mjs";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendorRoot = join(projectRoot, "vendor", "pi");
const vendorTsconfigPath = join(vendorRoot, "tsconfig.json");

let vendorTsconfig;
try {
	vendorTsconfig = JSON.parse(readFileSync(vendorTsconfigPath, "utf-8"));
} catch (error) {
	console.error(`Cannot read the vendored pi tsconfig at ${vendorTsconfigPath}`);
	console.error(`Run: npm run vendor:pi`);
	throw error;
}

const vendorPaths = vendorTsconfig.compilerOptions?.paths;
if (!vendorPaths) {
	throw new Error(`No compilerOptions.paths in ${vendorTsconfigPath}`);
}

// `paths` targets must be relative specifiers, i.e. start with `./` or `../`.
// `relative()` gives us `vendor/pi`, which tsgo rejects with TS5090, so we add
// the leading `./` explicitly.
const prefix = `./${relative(projectRoot, vendorRoot).split(sep).join("/")}`;

/** Targets look like `./packages/ai/src/index.ts`, so match on the package prefix. */
function isVendored(target) {
	return PI_PACKAGES.some((name) => target.startsWith(`packages/${name}/`));
}

const rewritten = {};
for (const [specifier, targets] of Object.entries(vendorPaths)) {
	// The bare "*" catch-all maps specifiers relative to the pi monorepo root,
	// which is only meaningful inside pi. Keeping it would shadow third-party
	// imports (e.g. "chalk" -> "vendor/pi/chalk").
	if (specifier === "*") continue;

	// Only keep targets that were actually vendored. A mapping pointing at a
	// package we did not copy is dead weight at best and a confusing failure at
	// worst.
	const kept = targets.map((target) => target.replace(/^\.\//, "")).filter(isVendored);

	if (kept.length === 0) continue;
	rewritten[specifier] = kept.map((target) => `${prefix}/${target}`);
}

const out = {
	$schema: "https://json.schemastore.org/tsconfig",
	_comment: "GENERATED by scripts/sync-pi-paths.mjs - do not edit by hand.",
	compilerOptions: {
		// The vendored source imports third-party packages (typebox, chalk, ...)
		// that now live in this project's own node_modules.
		typeRoots: ["./node_modules/@types"],
		paths: rewritten,
	},
};

const outPath = join(projectRoot, "tsconfig.pi-paths.json");
writeFileSync(outPath, `${JSON.stringify(out, null, "\t")}\n`, "utf-8");

const count = Object.keys(rewritten).length;
console.log(`Wrote ${outPath}`);
console.log(`  vendored pi : ${vendorRoot}`);
console.log(`  prefix      : ${prefix} (${PI_PACKAGES.join(", ")})`);
console.log(`  mappings    : ${count}`);
